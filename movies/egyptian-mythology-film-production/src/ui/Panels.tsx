import { useEffect, useState } from 'react';
import { narrator } from '../audio/narrator';
import { CHAPTERS } from '../film/chapters';
import { engine } from '../film/engine';
import { chapterStarts, formatTime, TOTAL_DURATION } from '../film/timeline';
import { useFilm } from '../film/useEngine';

const Shell = ({ title, onClose, children }: { title: string; onClose: () => void; children: React.ReactNode }) => (
  <div className="absolute bottom-[88px] right-4 z-40 max-h-[70%] w-[min(420px,calc(100%-2rem))] overflow-y-auto rounded-xl border border-[#d9a441]/30 bg-black/90 p-4 text-white shadow-2xl backdrop-blur" onClick={(e) => e.stopPropagation()}>
    <div className="mb-3 flex items-center justify-between"><h3 className="title-font text-sm uppercase tracking-[0.3em] text-[#d9a441]">{title}</h3><button onClick={onClose} className="rounded px-2 text-xl text-white/70 hover:text-white" aria-label="Close">×</button></div>
    {children}
  </div>
);

export function ChapterPanel({ onClose }: { onClose: () => void }) {
  const f = useFilm();
  return (
    <Shell title="Chapters" onClose={onClose}>
      <ul className="space-y-1">
        {CHAPTERS.map((c, i) => {
          const end = chapterStarts[i + 1] ?? TOTAL_DURATION;
          return (
            <li key={c.key}>
              <button onClick={() => { engine.seekChapter(i); onClose(); }} className={`flex w-full items-center gap-3 rounded-lg px-3 py-2 text-left transition hover:bg-white/10 ${f.chapter === i ? 'bg-[#d9a441]/15 ring-1 ring-[#d9a441]/40' : ''}`}>
                <span className="w-14 shrink-0 text-xs tabular-nums text-[#d9a441]">{formatTime(chapterStarts[i])}</span>
                <span className="min-w-0 flex-1"><span className="block truncate text-sm font-medium">{c.num ? `${c.num} · ` : ''}{c.title}</span><span className="block truncate text-xs text-white/55">{c.subtitle}</span></span>
                <span className="text-xs text-white/40">{Math.round((end - chapterStarts[i]) / 60)}m</span>
              </button>
            </li>
          );
        })}
      </ul>
    </Shell>
  );
}

export function SettingsPanel({ onClose }: { onClose: () => void }) {
  const f = useFilm();
  const [voices, setVoices] = useState(narrator.voices);
  useEffect(() => narrator.onVoices(() => setVoices([...narrator.voices])), []);
  const active = narrator.activeVoice;
  const row = 'mb-4 block text-xs uppercase tracking-widest text-white/60';
  const set = (p: Parameters<typeof engine.setPrefs>[0]) => { engine.setPrefs(p); engine.restartLine(); };
  return (
    <Shell title="Settings" onClose={onClose}>
      <label className={row}>Narrator voice
        <select className="mt-1 block w-full rounded bg-white/10 px-2 py-2 text-sm normal-case tracking-normal text-white" value={f.voiceURI || active?.voiceURI || ''} onChange={(e) => set({ voiceURI: e.target.value })} disabled={!narrator.available || !voices.length}>
          {!voices.length && <option>No English voices found</option>}
          {voices.map((v) => <option key={v.voiceURI} value={v.voiceURI} className="text-black">{v.name} ({v.lang})</option>)}
        </select>
      </label>
      <label className={row}>Speaking rate · {f.rate.toFixed(2)}
        <input type="range" min={0.6} max={1.2} step={0.01} value={f.rate} onChange={(e) => engine.setPrefs({ rate: +e.target.value })} onPointerUp={() => engine.restartLine()} className="mt-1 block w-full accent-[#d9a441]" />
      </label>
      <label className={row}>Voice pitch · {f.pitch.toFixed(2)}
        <input type="range" min={0.5} max={1.2} step={0.01} value={f.pitch} onChange={(e) => engine.setPrefs({ pitch: +e.target.value })} onPointerUp={() => engine.restartLine()} className="mt-1 block w-full accent-[#d9a441]" />
      </label>
      <div className="mb-4 flex items-center justify-between gap-2">
        <button className="rounded bg-white/10 px-3 py-1.5 text-sm hover:bg-white/20" onClick={() => narrator.speak('Before the pharaohs, before the pyramids, the gods shaped the world.', 'soft', () => undefined)}>Test voice</button>
        <label className="text-xs uppercase tracking-widest text-white/60">Quality
          <select className="ml-2 rounded bg-white/10 px-2 py-1.5 text-sm normal-case tracking-normal text-white" value={f.quality} onChange={(e) => engine.setPrefs({ quality: e.target.value as 'low' | 'medium' | 'high' })}>
            <option value="low" className="text-black">Low</option><option value="medium" className="text-black">Medium</option><option value="high" className="text-black">High (shadows)</option>
          </select>
        </label>
      </div>
      <p className="text-xs leading-relaxed text-white/50">Narration is generated by your browser’s built-in speech synthesis and is not a recorded human performance. For the best result choose a natural English male voice (for example the “Natural” voices in Microsoft Edge). Music and sound effects are synthesised live. Quality lowers automatically if playback becomes unsteady.</p>
      {!narrator.available && <p className="mt-2 text-xs text-amber-300">Speech synthesis is unavailable in this browser — the film will play with captions only.</p>}
    </Shell>
  );
}
